create or replace function public.handle_new_user() returns trigger
security definer set search_path = public language plpgsql as $$
begin
  insert into public.profiles(id,display_name,username,last_seen_at)
  values (
    new.id,
    left(coalesce(nullif(new.raw_user_meta_data->>'display_name',''),'Member'),80),
    lower(left(coalesce(nullif(new.raw_user_meta_data->>'username',''),'member_' || substr(replace(new.id::text,'-',''),1,8)),32)),
    now()
  );
  return new;
end $$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users for each row execute function public.handle_new_user();

create or replace function public.is_admin() returns boolean
language sql stable security definer set search_path = public as $$
  select exists(select 1 from public.profiles where id=auth.uid() and role in ('admin','moderator'));
$$;

create or replace function public.increment_topic_views(target_id bigint) returns void
language sql security definer set search_path = public as $$
  update public.forum_topics set views=views+1 where id=target_id;
$$;

create or replace function public.resolve_login_email(login_username text) returns text
language sql security definer set search_path = public,auth as $$
  select u.email from public.profiles p join auth.users u on u.id=p.id
  where p.username=lower(trim(login_username)) limit 1;
$$;
revoke all on function public.resolve_login_email(text) from public,anon,authenticated;
grant execute on function public.resolve_login_email(text) to service_role;

