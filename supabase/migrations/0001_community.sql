create extension if not exists citext;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name varchar(80) not null,
  username citext not null unique check (username::text ~ '^[a-z0-9_]{3,32}$'),
  role text not null default 'user' check (role in ('user','moderator','admin')),
  bio varchar(600) not null default '',
  avatar_path text,
  banner_path text,
  accent_primary varchar(7) not null default '#f2eb00' check (accent_primary ~ '^#[0-9a-fA-F]{6}$'),
  accent_secondary varchar(7) not null default '#7c3aed' check (accent_secondary ~ '^#[0-9a-fA-F]{6}$'),
  profile_effect text not null default 'aurora' check (profile_effect in ('aurora','nebula','ember','ocean','none')),
  avatar_scale numeric(3,2) not null default 1 check (avatar_scale between 1 and 2),
  avatar_x smallint not null default 50 check (avatar_x between 0 and 100),
  avatar_y smallint not null default 50 check (avatar_y between 0 and 100),
  banner_y smallint not null default 50 check (banner_y between 0 and 100),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  last_seen_at timestamptz
);

create table if not exists public.post_comments (
  id bigint generated by default as identity primary key,
  post_slug varchar(120) not null,
  user_id uuid not null references public.profiles(id) on delete cascade,
  body text not null check (char_length(body) between 1 and 5000),
  is_deleted boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.forum_topics (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  category text not null check (category in ('suggestion','bugs','website-error','fatal-error','downtime')),
  title varchar(160) not null check (char_length(title) between 6 and 160),
  slug varchar(190) not null unique check (slug ~ '^[a-z0-9][a-z0-9-]{0,189}$'),
  body text not null check (char_length(body) between 10 and 20000),
  status text not null default 'open' check (status in ('open','closed','solved')),
  solution_reply_id bigint,
  views integer not null default 0 check (views >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.forum_replies (
  id bigint generated by default as identity primary key,
  topic_id bigint not null references public.forum_topics(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  parent_id bigint references public.forum_replies(id) on delete cascade,
  body text not null check (char_length(body) between 1 and 10000),
  is_deleted boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

do $$ begin
  alter table public.forum_topics add constraint forum_topics_solution_reply_fk
    foreign key (solution_reply_id) references public.forum_replies(id) on delete set null;
exception when duplicate_object then null; end $$;

create table if not exists public.forum_topic_votes (
  topic_id bigint not null references public.forum_topics(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  vote smallint not null check (vote in (-1,1)),
  updated_at timestamptz not null default now(),
  primary key (topic_id,user_id)
);

create table if not exists public.forum_reply_votes (
  reply_id bigint not null references public.forum_replies(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  vote smallint not null check (vote in (-1,1)),
  updated_at timestamptz not null default now(),
  primary key (reply_id,user_id)
);

create index if not exists comments_post_idx on public.post_comments(post_slug,created_at);
create index if not exists topics_activity_idx on public.forum_topics(category,updated_at desc);
create index if not exists replies_topic_idx on public.forum_replies(topic_id,created_at);

create or replace function public.touch_updated_at() returns trigger language plpgsql as $$
begin new.updated_at = now(); return new; end $$;

create or replace function public.validate_forum_reply_reference() returns trigger
language plpgsql as $$
begin
  if new.parent_id is not null and
     not exists(select 1 from public.forum_replies p where p.id=new.parent_id and p.topic_id=new.topic_id) then
    raise exception 'Parent reply must belong to the same topic.';
  end if;
  return new;
end $$;

create or replace function public.validate_forum_topic_solution() returns trigger
language plpgsql as $$
begin
  if new.solution_reply_id is not null and
     not exists(select 1 from public.forum_replies r where r.id=new.solution_reply_id and r.topic_id=new.id) then
    raise exception 'Solution reply must belong to this topic.';
  end if;
  return new;
end $$;

